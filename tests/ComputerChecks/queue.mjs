import assert from 'node:assert/strict';
import { parsePlan, executeQueue, readPlanStream } from '../../integrations/dsh/queue.mjs';
const plan = JSON.stringify({ steps: [{ title: 'Open test app', verify: 'Window exists', action:'open_app' }, { title: 'Select Chat', verify: 'Chat is selected', action:'click' }] });
assert.throws(() => parsePlan('{"steps":[]}'));
assert.throws(() => parsePlan(JSON.stringify({ steps: Array(7).fill({ title: 'Extra', verify: 'Visible' }) })));
assert.throws(() => parsePlan('{"steps":[{"title":"Missing check"}]}'));
let prompts = [], states = [];
let result = await executeQueue({ goal: 'Open test app, then select Chat', plan: async () => plan, publish: async state => states.push(structuredClone(state)), runStep: async (prompt, index) => { prompts.push(prompt); return index ? 'Chat selected; inspected current label' : 'Window exists; inspected window title'; } });
assert.equal(result.steps.every(s => s.status === 'done'), true);
assert.equal(prompts.length, 2);
assert(!prompts[0].includes('Window exists; inspected'));
assert(prompts[1].includes('Window exists; inspected window title'));
assert(!prompts[1].includes('screenshot_base64'));
assert.deepEqual(states.map(s => s.phase), ['planning', 'running', 'running', 'done']);
assert.equal(states[2].steps[0].status, 'done');
let attempts = 0;
result = await executeQueue({ goal: 'Open app and select Chat', plan: async () => plan, publish: async () => {}, runStep: async () => { if (++attempts === 2) throw new Error('User declined'); return 'Window verified'; } });
assert.equal(attempts, 2);
assert.equal(result.steps[0].status, 'done');
assert.equal(result.steps[1].status, 'blocked');
assert(result.reply.includes('Completed actions were not retried'));
attempts = 0;
result = await executeQueue({ goal: 'Open app', plan: async () => 'malformed', publish: async () => {}, runStep: async () => attempts++ });
assert.equal(attempts, 0);
assert(result.reply.includes('No queued action ran'));
await assert.rejects(executeQueue({ goal: 'x'.repeat(4001), plan: async () => plan, publish: async () => {}, runStep: async () => {} }));
await assert.rejects(executeQueue({ goal: 'Open app', plan: async () => plan, publish: async () => { throw new Error('Stopped'); }, runStep: async () => attempts++ }), /Stopped/);
assert.equal(attempts, 0);
const stream = frames => new Response(frames.map(frame => 'data: ' + JSON.stringify(frame) + '\n\n').join('') + 'data: [DONE]\n\n');
assert.equal(await readPlanStream(stream([{ choices: [{ delta: { content: plan }, finish_reason: 'stop' }] }])), plan);
await assert.rejects(readPlanStream(stream([{ choices: [{ delta: { content: plan }, finish_reason: 'length' }] }])));
await assert.rejects(readPlanStream(stream([{ choices: [{ delta: { tool_calls: [{ function: { name: 'computer_click' } }] }, finish_reason: 'tool_calls' }] }])));
console.log('PASS queue validates bounded plans, starts focused steps, carries only verified summaries, preserves completed work and stops on failure/cancellation without replay');
